            m_auroraEmitters.Clear();
        }

        private void CleanupGeneratedObjects()
        {
            Scene scene = m_scene;
            if (scene == null)
                return;

            List<SceneObjectGroup> delete = new List<SceneObjectGroup>();
            foreach (SceneObjectGroup group in scene.GetSceneObjectGroups())
            {
                if (group == null || group.IsDeleted || group.Backup)
                    continue;

                if (IsWeatherGeneratedGroup(group))
                    delete.Add(group);
            }

            if (delete.Count == 0)
                return;

            DeleteEmitters(delete);
            m_log.WarnFormat(
                "[WEATHER]: Removed {0} non-persistent weather object(s) left in {1} by an earlier module instance.",
                delete.Count,
                scene.RegionInfo.RegionName);
        }

        private bool IsWeatherGeneratedGroup(SceneObjectGroup group)
        {
            if (group == null || group.RootPart == null)
                return false;

            string name = group.Name ?? string.Empty;
            if (name.StartsWith(GeneratedNamePrefix, StringComparison.OrdinalIgnoreCase))
                return true;

            if (group.RootPart.Description == GeneratedDescription)
                return true;

            return string.Equals(name, "weather lightning flash", StringComparison.OrdinalIgnoreCase)
                || name.StartsWith("weather rain emitter", StringComparison.OrdinalIgnoreCase)
                || name.StartsWith("weather storm emitter", StringComparison.OrdinalIgnoreCase)
                || name.StartsWith("weather snow emitter", StringComparison.OrdinalIgnoreCase)
                || string.Equals(name, "weather puddle", StringComparison.OrdinalIgnoreCase)
                || string.Equals(name, "weather snow accumulation", StringComparison.OrdinalIgnoreCase);
        }

        private void RefreshExclusionVolumes(bool force)
        {
            if (!m_useExclusionVolumes)
                return;

            DateTime now = DateTime.UtcNow;
            lock (m_sync)
            {
                if (!force && now < m_nextExclusionRefreshUtc)
                    return;
                m_nextExclusionRefreshUtc = now.AddSeconds(m_exclusionRefreshSeconds);
            }

            Scene scene = m_scene;
            if (scene == null)
                return;

            List<ExclusionVolume> volumes = new List<ExclusionVolume>();
            foreach (SceneObjectGroup group in scene.GetSceneObjectGroups())
            {
                if (group == null || group.IsDeleted || IsWeatherGeneratedGroup(group))
                    continue;

                string name = group.Name ?? string.Empty;
                bool matches = string.Equals(name, m_exclusionObjectName, StringComparison.OrdinalIgnoreCase)
                    || name.StartsWith(m_exclusionObjectName + " ", StringComparison.OrdinalIgnoreCase)
                    || name.StartsWith(m_exclusionObjectName + " -", StringComparison.OrdinalIgnoreCase);

                if (!matches)
                    continue;

                try
                {
                    group.GetAxisAlignedBoundingBoxRaw(
                        out float minX,
                        out float maxX,
                        out float minY,
                        out float maxY,
                        out float minZ,
                        out float maxZ);

                    volumes.Add(new ExclusionVolume
                    {
                        MinX = minX,
                        MaxX = maxX,
                        MinY = minY,
                        MaxY = maxY,
                        MinZ = minZ,
                        MaxZ = maxZ
                    });
                }
                catch (Exception e)
                {
                    m_log.DebugFormat("[WEATHER]: Could not read exclusion volume '{0}': {1}", name, e.Message);
                }
            }

            lock (m_sync)
            {
                m_exclusionVolumes.Clear();
                m_exclusionVolumes.AddRange(volumes);
            }
        }

        private bool IsInsideExclusionVolume(float x, float y)
        {
            if (!m_useExclusionVolumes)
                return false;

            RefreshExclusionVolumes(false);
            lock (m_sync)
            {
                foreach (ExclusionVolume volume in m_exclusionVolumes)
                {
                    if (volume.ContainsXY(x, y))
                        return true;
                }
            }

            return false;
        }

        // ── [Confluence] The weather sky, per viewer ─────────────────────────────────────────────────────────────────
        //
        // The weather sky is each avatar's own environment override (ScenePresence.Environment, which the environment
        // module serves before the parcel's and the region's), never the region's stored environment. It used to be
        // written to the region (FromLightShare), so a crash, a forced stop or a restart before the clean-up left the
        // storm sky saved, and the module, starting at Clear, never took it off ("stuck until weather clear").
        //
        // The override is a copy of the region's day cycle with the weather applied to every sky in it, so the sun
        // and moon keep moving. An avatar standing on a parcel with its own environment, or one a script has given its
        // own (llReplaceAgentEnvironment, osReplaceAgentEnvironment), is left alone.

        /// <summary>The override the module last gave avatars; null when no weather sky is showing.</summary>
        private ViewerEnvironment m_weatherEnvironment;

        // The sky that is showing (m_skyShown) and the one it is fading to. Each step builds the override from the
        // region's environment as it is then, so an owner's change to the day cycle shows through.
        private readonly object m_skySync = new object();
        private SkyEffect m_skyFrom;
        private SkyEffect m_skyTo;
        private SkyEffect m_skyShown;
        private DateTime m_skyFadeStartUtc;
        private Timer m_skyFadeTimer;

        private void ApplyClouds(WeatherKind weather)
        {
            if (!m_adjustClouds || m_environmentModule == null)
                return;

            // A weather without a sky of its own (sunny, clear) fades back to the region's sky.
            m_skyEffects.TryGetValue(weather, out SkyEffect target);
            StartSkyFade(target, false);
        }

        /// <summary>
        /// Fade from what is showing to <paramref name="target"/> (null: the region's own sky) over SkyFadeSeconds, or
        /// at once.
        /// </summary>
        private void StartSkyFade(SkyEffect target, bool immediate)
        {
            lock (m_skySync)
            {
                m_skyFrom = m_skyShown;
                m_skyTo = target;
                m_skyFadeStartUtc = DateTime.UtcNow;

                if (immediate || m_skyFadeSeconds <= 0f || (m_skyFrom == null && m_skyTo == null))
                {
                    StopSkyFadeTimer();
                    ShowSky(target);
                    return;
                }

                ShowSky(SkyEffect.Lerp(m_skyFrom, m_skyTo, 0f));
                if (m_skyFadeTimer == null)
                {
                    int step = (int)(m_skyFadeStepSeconds * 1000f);
                    m_skyFadeTimer = new Timer(_ => SkyFadeStep(), null, step, step);
                }
            }
        }

        private void SkyFadeStep()
        {
            try
            {
                lock (m_skySync)
                {
                    if (m_skyFadeTimer == null)
                        return;
                    float t = (float)((DateTime.UtcNow - m_skyFadeStartUtc).TotalSeconds / m_skyFadeSeconds);
                    if (t >= 1f)
                    {
                        StopSkyFadeTimer();
                        ShowSky(m_skyTo);
                        return;
                    }
                    ShowSky(SkyEffect.Lerp(m_skyFrom, m_skyTo, t));
                }
            }
            catch (Exception e)
            {
                m_log.WarnFormat("[WEATHER]: sky fade step failed: {0}", e.Message);
            }
        }

        private void StopSkyFadeTimer()
        {
            Timer timer = m_skyFadeTimer;
            m_skyFadeTimer = null;
            timer?.Dispose();
        }

        /// <summary>Give the avatars the region's sky with <paramref name="effect"/> applied (null or neutral: no override).</summary>
        private void ShowSky(SkyEffect effect)
        {
            if (effect != null && effect.IsNeutral)
                effect = null;
            m_skyShown = effect;

            ViewerEnvironment next = null;
            if (effect != null && m_environmentModule != null)
            {
                ViewerEnvironment regionEnvironment = m_environmentModule.GetRegionEnvironment();
                if (regionEnvironment != null)
                {
                    next = regionEnvironment.Clone();
                    foreach (SkyData sky in next.SkyFrames)
                        effect.ApplyTo(sky);
                }
            }

            ViewerEnvironment previous = m_weatherEnvironment;
            m_weatherEnvironment = next;
            if (previous != null || next != null)
                ForEachWeatherAvatar(sp => SetAvatarSky(sp, previous, next));
        }

        /// <summary>Back to the region's own sky: at once when <paramref name="force"/>, else faded.</summary>
        private void RestoreClouds(bool force)
        {
            if (m_environmentModule == null)
                return;
            if (m_skyShown == null && m_skyTo == null && m_weatherEnvironment == null)
                return;
            StartSkyFade(null, force);
        }

        /// <summary>The avatars the weather sky is for: root, not NPCs.</summary>
        private void ForEachWeatherAvatar(Action<ScenePresence> action)
        {
            Scene scene = m_scene;
            if (scene == null)
                return;
            scene.ForEachRootScenePresence(sp =>
            {
                if (!sp.IsNPC && !sp.IsDeleted)
                    action(sp);
            });
        }

        /// <summary>
        /// Gives an avatar <paramref name="next"/> (null: no weather sky) if its environment is the module's own or
        /// none at all, and it is not on a parcel with an environment of its own; then tells its viewer.
        /// </summary>
        private void SetAvatarSky(ScenePresence sp, ViewerEnvironment previous, ViewerEnvironment next)
        {
            try
            {
                ViewerEnvironment current = sp.Environment;
                bool ours = current == null || (previous != null && ReferenceEquals(current, previous));
                if (!ours)
                    return;

                if (next != null)
                {
                    ILandObject land = m_scene?.LandChannel?.GetLandObject(sp.AbsolutePosition.X, sp.AbsolutePosition.Y);
                    if (land?.LandData?.Environment != null)
                        next = null;
                }

                if (ReferenceEquals(current, next))
                    return;
                sp.Environment = next;
                m_environmentModule?.WindlightRefreshForced(sp, 2);
            }
            catch (Exception e)
            {
                m_log.DebugFormat("[WEATHER]: Could not set the weather sky for {0}: {1}", sp.Name, e.Message);
            }
        }

        /// <summary>
        /// A weather sky the old module left saved on the region: a LightShare environment (what FromLightShare
        /// stores) whose clouds are exactly one of the weather profiles'. Put back to the region's default, as
        /// "weather clear" did. Anything else - an owner's own environment - is left as it is.
        /// </summary>
        private void HealSavedWeatherSky()
        {
            if (m_environmentModule == null || m_scene == null)
                return;
            try
            {
                ViewerEnvironment env = m_environmentModule.GetRegionEnvironment();
                if (env == null || !env.IsLightShare)
                    return;
                foreach (SkyData sky in env.SkyFrames)
                {
                    foreach (var p in s_legacySavedSkies)
                    {
                        if (Math.Abs(sky.cloud_shadow - p.Cover) < 0.0005f && Math.Abs(sky.cloud_scale - p.Scale) < 0.0005f
                            && Math.Abs(sky.cloud_color.X - p.R) < 0.0005f && Math.Abs(sky.cloud_color.Y - p.G) < 0.0005f)
                        {
                            m_environmentModule.ResetEnvironmentSettings(m_scene.RegionInfo.RegionID);
                            m_log.InfoFormat("[WEATHER]: {0} had a {1} sky saved by an earlier weather version; put back to the region default.",
                                m_scene.RegionInfo.RegionName, p.Kind);
                            return;
                        }
                    }
                }
            }
            catch (Exception e)
            {
                m_log.WarnFormat("[WEATHER]: Could not check {0} for a saved weather sky: {1}", m_scene.RegionInfo.RegionName, e.Message);
            }
        }


        // ── [Confluence] On or off per region, from the web portal ──────────────────────────────────────────────────

        private static readonly System.Net.Http.HttpClient s_settingsHttp = new System.Net.Http.HttpClient { Timeout = TimeSpan.FromSeconds(5) };
        private const int WebSettingsFirstPollMS = 5000, WebSettingsPollMS = 60000;
        private long m_lastWebSettingsWarnMs;

        // A Robust that is still starting answers 404 for a moment, before its handlers are registered, so a 404 is
        // "no answer yet" until it has lasted this long; only then is it taken for an older Robust without the endpoint.
        private long m_webSettings404FallbackMs = 600000;
        private long m_first404Ms;

        private bool UsesWebSettings => m_useWebSettings && m_webSettingsAvailable && m_settingsServerURI.Length > 0;

        /// <summary>
        /// Turns the region's weather on (timers started, the cycle's first change soon) or off (any weather cleared,
        /// the sky given back, every timer stopped). Called with the owner's choice or, without the portal, at startup.
        /// </summary>
        private void SetRegionActive(bool active, string why)
        {
            lock (m_weatherChangeSync)
            {
                if (active == m_regionActive || m_scene == null)
                    return;
                m_regionActive = active;
                string region = m_scene.RegionInfo.RegionName;

                if (active)
                {
                    StartAutoCycle(true);
                    StartAuroraTimer();
                    StartLightningSweepTimer();
                    m_log.InfoFormat("[WEATHER]: Weather on in {0} ({1}).", region, why);
                }
                else
                {
                    StopAutoCycle();
                    StopActiveAreaRefresh();
                            StopAuroraTimer();
                    StopLightningSweepTimer();
                    RemoveAuroraEmitters();
                    ClearWeather(false, true, true);
                    m_log.InfoFormat("[WEATHER]: Weather off in {0} ({1}).", region, why);
                }
            }
        }

        private void StartWebSettingsPolling()
        {
            StopWebSettingsPolling();
            m_webSettingsTimer = new Timer(_ => PollWebSettings(), null, WebSettingsFirstPollMS, WebSettingsPollMS);
            m_log.InfoFormat("[WEATHER]: {0} follows its owner's weather setting from the web portal (off until turned on).",
                m_scene?.RegionInfo.RegionName);
        }

        private void StopWebSettingsPolling()
        {
            Timer timer = m_webSettingsTimer;
            m_webSettingsTimer = null;
            timer?.Dispose();
        }

        private void PollWebSettings()
        {
            Scene scene = m_scene;
            // polled on after an ini fallback too, so a Robust that later answers hands the choice back to the owner
            if (scene == null || !m_useWebSettings || m_settingsServerURI.Length == 0)
                return;

            string url = m_settingsServerURI + "/weather/" + scene.RegionInfo.RegionID;
            try
            {
                using var response = s_settingsHttp.GetAsync(url).GetAwaiter().GetResult();
                if (response.StatusCode == System.Net.HttpStatusCode.NotFound)
                {
                    // Robust starting up (its handlers not registered yet) or a Robust without the endpoint (an older
                    // build). Only a 404 that lasts is the second: then the ini decides, as before this feature.
                    long now404 = Environment.TickCount64;
                    if (m_first404Ms == 0)
                        m_first404Ms = now404;
                    if (!m_webSettingsAvailable || now404 - m_first404Ms < m_webSettings404FallbackMs)
                        return;

                    m_webSettingsAvailable = false;
                    m_log.WarnFormat("[WEATHER]: {0} has answered 404 for the region weather settings for {1} minutes; {2} uses the [Weather] ini settings until it answers.",
                        m_settingsServerURI, m_webSettings404FallbackMs / 60000, scene.RegionInfo.RegionName);
                    m_autoCycleEnabled = m_iniAutoCycleEnabled;
                    m_autoCycleHours = m_iniAutoCycleHours;
                    SetRegionActive(true, "the [Weather] ini settings");
                    return;
                }
                response.EnsureSuccessStatusCode();
                string json = response.Content.ReadAsStringAsync().GetAwaiter().GetResult();
                m_first404Ms = 0;
                if (!m_webSettingsAvailable)
                {
                    m_webSettingsAvailable = true;
                    m_log.InfoFormat("[WEATHER]: {0} answers the region weather settings again; {1} follows its owner's setting.",
                        m_settingsServerURI, scene.RegionInfo.RegionName);
                }
                ApplyWebSettings(OSDParser.DeserializeJson(json) as OSDMap);
            }
            catch (Exception e)
            {
                // Robust unreachable: keep what the region has (at startup, off) and say so now and then.
                long now = Environment.TickCount64;
                if (now - m_lastWebSettingsWarnMs > 600000)
                {
                    m_lastWebSettingsWarnMs = now;
                    m_log.WarnFormat("[WEATHER]: Could not read the weather settings of {0} from {1}: {2}",
                        scene.RegionInfo.RegionName, m_settingsServerURI, e.Message);
                }
            }
        }

        /// <summary>
        /// The owner's choice, read as the My Regions page shows it: "enabled" (absent: off), "autocycle" (absent: on)
        /// and "cyclehours" (absent: 1 hour).
        /// </summary>
        private void ApplyWebSettings(OSDMap map)
        {
            if (map == null || m_scene == null)
                return;

            bool enabled = map.TryGetValue("enabled", out OSD e) && string.Equals(e.AsString(), "true", StringComparison.OrdinalIgnoreCase);
            bool autoCycle = map.TryGetValue("autocycle", out OSD a)
                ? string.Equals(a.AsString(), "true", StringComparison.OrdinalIgnoreCase)
                : true;
            float hours = 1f;
            if (map.TryGetValue("cyclehours", out OSD h)
                && float.TryParse(h.AsString(), NumberStyles.Float, CultureInfo.InvariantCulture, out float parsed))
                hours = Clamp(parsed, 0.25f, 24f);

            lock (m_weatherChangeSync)
            {
                bool cycleChanged = autoCycle != m_autoCycleEnabled || Math.Abs(hours - m_autoCycleHours) > 0.001f;
                m_autoCycleEnabled = autoCycle;
                m_autoCycleHours = hours;

                if (enabled != m_regionActive)
                    SetRegionActive(enabled, "set by the region's owner");
                else if (enabled && cycleChanged)
                {
                    if (autoCycle)
                        StartAutoCycle(false);
                    else
                        StopAutoCycle();
                    m_log.InfoFormat("[WEATHER]: {0}: automatic changes {1}, every {2:0.##} hours.",
                        m_scene.RegionInfo.RegionName, autoCycle ? "on" : "off", hours);
                }
            }
        }

        private void ApplyWind(WeatherKind weather)
        {
            if (!m_adjustWind || m_windModule == null)
                return;

            string plugin = m_windModule.WindActiveModelPluginName;
            if (string.IsNullOrEmpty(plugin))
                return;

            try
            {
                SaveWindParams(plugin);

                float strength = WeatherWindStrength(weather);
                if (plugin == "SimpleRandomWind")
                {
                    m_windModule.WindParamSet(plugin, "strength", strength * 4f);
                }
                else if (plugin == "ConfigurableWind")
                {
                    m_windModule.WindParamSet(plugin, "avgStrength", strength * 4f);
                    m_windModule.WindParamSet(plugin, "avgDirection", m_windDirectionDegrees);
                    m_windModule.WindParamSet(plugin, "varStrength", Math.Max(0.5f, strength * 1.6f));
                    m_windModule.WindParamSet(plugin, "varDirection", m_windDirectionVarianceDegrees);
                    m_windModule.WindParamSet(plugin, "rateChange", (weather == WeatherKind.Storm || weather == WeatherKind.Blizzard) ? 1.8f : 0.8f);
                }
            }
            catch (Exception e)
            {
                string regionName = m_scene == null ? "unknown region" : m_scene.RegionInfo.RegionName;
                m_log.WarnFormat("[WEATHER]: Could not apply weather wind in {0}: {1}", regionName, e.Message);
                throw;
            }
        }

        private void SaveWindParams(string plugin)
        {
            if (m_savedWindParams != null)
                return;

            Dictionary<string, float> saved = new Dictionary<string, float>();

            if (plugin == "SimpleRandomWind")
            {
                saved["strength"] = m_windModule.WindParamGet(plugin, "strength");
            }
            else if (plugin == "ConfigurableWind")
            {
                saved["avgStrength"] = m_windModule.WindParamGet(plugin, "avgStrength");
                saved["avgDirection"] = m_windModule.WindParamGet(plugin, "avgDirection");
                saved["varStrength"] = m_windModule.WindParamGet(plugin, "varStrength");
                saved["varDirection"] = m_windModule.WindParamGet(plugin, "varDirection");
                saved["rateChange"] = m_windModule.WindParamGet(plugin, "rateChange");
            }

            if (saved.Count == 0)
                return;

            m_savedWindPlugin = plugin;
            m_savedWindParams = saved;
        }

        private void RestoreWind(bool force)
        {
            if (m_savedWindParams == null || string.IsNullOrEmpty(m_savedWindPlugin))
                return;

            if (!force && !m_restoreWindOnClear)
                return;

            if (m_windModule == null)
                return;

            try
            {
                foreach (KeyValuePair<string, float> windParam in m_savedWindParams)
                    m_windModule.WindParamSet(m_savedWindPlugin, windParam.Key, windParam.Value);

                m_savedWindPlugin = null;
                m_savedWindParams = null;
            }
            catch (Exception e)
            {
                string regionName = m_scene == null ? "unknown region" : m_scene.RegionInfo.RegionName;
                m_log.WarnFormat("[WEATHER]: Could not restore weather wind in {0}: {1}", regionName, e.Message);
            }
        }

        private void DeleteEmitters(List<SceneObjectGroup> emitters)
        {
            if (m_scene == null)
                return;

            foreach (SceneObjectGroup emitter in emitters)
            {
                if (emitter == null || emitter.IsDeleted)
                    continue;

                try
                {
                    m_scene.DeleteSceneObject(emitter, false, false);
                }
                catch (Exception e)
                {
                    m_log.DebugFormat("[WEATHER]: Failed to delete weather emitter {0}: {1}", emitter.UUID, e.Message);
                }
            }
        }

        private static bool IsWeatherCommand(string request)
        {
            string[] tokens = CommandTokens(request);
            return tokens.Length > 0 && (tokens[0] == "weather" || tokens[0] == "meteo");
        }

        private bool TryResolveWeather(string request, out WeatherKind weather)
        {
            string token = WeatherToken(request);
            switch (token)
            {
                case "clear":
                case "stop":
                case "asciutto":
                    weather = WeatherKind.Clear;
                    return true;

                case "sunny":
                case "sun":
                case "sereno":
                case "sole":
                    weather = WeatherKind.Sunny;
                    return true;

                case "storm":
                case "temporale":
                case "tempesta":
                    weather = WeatherKind.Storm;
                    return true;

                case "snow":
                case "neve":
                case "nevica":
                    weather = WeatherKind.Snow;
                    return true;

                case "blizzard":
                case "snowstorm":
                case "bufera":
                    weather = WeatherKind.Blizzard;
                    return true;

                case "rain":
                case "pioggia":
                case "piove":
                    weather = WeatherKind.Rain;
                    return true;

                default:
                    weather = WeatherKind.Clear;
                    return false;
            }
        }

        private static bool IsStatusCommand(string request)
        {
            string[] tokens = CommandTokens(request);
            if (tokens.Length == 0)
                return false;

            if ((tokens[0] == "weather" || tokens[0] == "meteo") && tokens.Length == 1)
                return true;

            string token = WeatherToken(request);
            return token == "status" || token == "stato";
        }

        private static string WeatherToken(string request)
        {
            string[] tokens = CommandTokens(request);
            if (tokens.Length == 0)
                return string.Empty;

            if (tokens[0] == "weather" || tokens[0] == "meteo")
                return tokens.Length > 1 ? tokens[1] : string.Empty;

            return tokens[0];
        }

        private static string[] CommandTokens(string request)
        {
            return (request ?? string.Empty)
                .Trim()
                .ToLower(CultureInfo.InvariantCulture)
                .Split(new[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
        }

        private void SendStatus(IClientAPI client)
        {
            int emitterCount;
            int exclusionVolumeCount;
            WeatherKind weather;

            lock (m_weatherChangeSync)
            {
                lock (m_sync)
                {
                    emitterCount = m_emitters.Count;
                    exclusionVolumeCount = m_exclusionVolumes.Count;
                    weather = m_currentWeather;
                }
            }

            SendReply(client, BuildWeatherReport(weather, emitterCount, exclusionVolumeCount));
        }

        private string BuildWeatherReport(WeatherKind weather, int emitterCount, int exclusionVolumeCount)
        {
            Scene scene = m_scene;
            string regionName = scene == null ? "the region" : scene.RegionInfo.RegionName;
            float temperatureC = m_temperatureC;

            StringBuilder sb = new StringBuilder();
            sb.AppendFormat(CultureInfo.InvariantCulture, "Weather report for {0}: ", regionName);
            sb.Append(WeatherNarrative(weather));
            sb.AppendFormat(
                CultureInfo.InvariantCulture,
                " {0:0.#}C and {1}.",
                temperatureC,
                TemperatureDescriptor(temperatureC));

            if (IsPrecipitationWeather(weather))
            {
                sb.AppendFormat(
                    CultureInfo.InvariantCulture,
                    " Coverage: {0} ({1} emitters).",
                    CoverageModeName(m_coverageMode),
                    emitterCount);
            }

            if (exclusionVolumeCount > 0)
            {
                sb.AppendFormat(
                    CultureInfo.InvariantCulture,
                    " {0} exclusion volume{1} active.",
                    exclusionVolumeCount,
                    exclusionVolumeCount == 1 ? string.Empty : "s");
            }

            sb.AppendFormat(CultureInfo.InvariantCulture, " Next forecast: {0}.", FormatNextForecast());

            return sb.ToString();
        }

        private static string WeatherNarrative(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Rain:
                    return "Rain is falling.";
                case WeatherKind.Storm:
                    return "A storm is raging, with heavy rain and lightning.";
                case WeatherKind.Snow:
                    return "Snow is falling.";
                case WeatherKind.Blizzard:
                    return "A blizzard is raging, with heavy snow and wind.";
                case WeatherKind.Sunny:
                    return "Skies are sunny and clear.";
                default:
                    return "Skies are clear.";
            }
        }

        private static string TemperatureDescriptor(float temperatureC)
        {
            if (temperatureC <= -10f)
                return "bitterly cold";
            if (temperatureC <= 0f)
                return "freezing";
            if (temperatureC <= 10f)
                return "cold";
            if (temperatureC <= 18f)
                return "cool";
            if (temperatureC <= 24f)
                return "mild";
            if (temperatureC <= 30f)
                return "warm";
            return "hot";
        }

        private void AnnounceWeatherChange(WeatherKind weather)
        {
            if (!m_announceWeatherInChat)
                return;

            Scene scene = m_scene;
            if (scene == null)
                return;

            int emitterCount;
            int exclusionVolumeCount;
            lock (m_weatherChangeSync)
            {
                lock (m_sync)
                {
                    emitterCount = m_emitters.Count;
                    exclusionVolumeCount = m_exclusionVolumes.Count;
                }
            }

            string report = BuildWeatherReport(weather, emitterCount, exclusionVolumeCount);
            scene.ForEachRootScenePresence(sp =>
            {
                if (sp != null && !sp.IsDeleted && sp.ControllingClient != null)
                    SendRegionWeatherMessage(sp, report);
            });
        }

        // "WEATHER|<kind>" on a fixed region-wide channel - the same shape
        // residents' own scripted FX prims (fireplaces, seasonal clothing,
        // umbrellas) already used before this module existed, so a receiver
        // built against that older convention keeps working unmodified. This
        // is the server-side equivalent of llRegionSay: IWorldComm is what
        // actually fans a message out to every llListen() registered on the
        // matching channel, the same delivery path llRegionSay itself uses.
        private void BroadcastWeatherToScripts(WeatherKind weather)
        {
            if (!m_broadcastWeatherToScripts)
                return;

            Scene scene = m_scene;
            if (scene == null)
                return;

            IWorldComm worldComm = scene.RequestModuleInterface<IWorldComm>();
            if (worldComm == null)
                return;

            string message = "WEATHER|" + BroadcastWeatherToken(weather);
            worldComm.DeliverMessage(
                ChatTypeEnum.Region, m_weatherBroadcastChannel, Name, scene.RegionInfo.RegionID, message);
        }

        // Deliberately separate from WeatherName() (lowercase, for human-
        // readable chat/log text) - existing FX receiver scripts compare
        // this token with an exact case-sensitive string match.
        private static string BroadcastWeatherToken(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Sunny:
                    return "Sunny";
                case WeatherKind.Rain:
                    return "Rain";
                case WeatherKind.Storm:
                    return "Storm";
                case WeatherKind.Snow:
                    return "Snow";
                case WeatherKind.Blizzard:
                    return "Blizzard";
                default:
                    return "Clear";
            }
        }

        private void UpdateTemperatureForWeather(WeatherKind weather)
        {
            float baseTemp = WeatherBaseTemperatureC(weather);
            float jitter = m_temperatureVarianceC > 0f
                ? RandomRange(-m_temperatureVarianceC, m_temperatureVarianceC)
                : 0f;
            m_temperatureC = Clamp(baseTemp + jitter, -100f, 100f);
        }

        private float WeatherBaseTemperatureC(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Sunny:
                    return m_sunnyTemperatureC;
                case WeatherKind.Rain:
                    return m_rainTemperatureC;
                case WeatherKind.Storm:
                    return m_stormTemperatureC;
                case WeatherKind.Snow:
                    return m_snowTemperatureC;
                case WeatherKind.Blizzard:
                    return m_blizzardTemperatureC;
                default:
                    return m_clearTemperatureC;
            }
        }

        private void SendWeatherIM(UUID agentID)
        {
            Scene scene = m_scene;
            if (scene == null || string.IsNullOrEmpty(m_weatherIMMessage))
                return;

            ScenePresence sp = scene.GetScenePresence(agentID);
            if (sp == null || sp.IsDeleted || sp.IsNPC || sp.IsChildAgent || sp.ControllingClient == null)
                return;

            GridInstantMessage msg = new GridInstantMessage
            {
                imSessionID = UUID.Random().Guid,
                fromAgentID = UUID.Zero.Guid,
                toAgentID = agentID.Guid,
                timestamp = (uint)Util.UnixTimeSinceEpoch(),
                fromAgentName = "Weather",
                message = FormatWeatherIMMessage(scene),
                dialog = (byte)InstantMessageDialog.MessageFromAgent,
                fromGroup = false,
                offline = (byte)0,
                ParentEstateID = 0,
                Position = sp.AbsolutePosition,
                RegionID = scene.RegionInfo.RegionID.Guid,
                binaryBucket = Array.Empty<byte>()
            };

            sp.ControllingClient.SendInstantMessage(msg);
        }

        private string FormatForecastWarningMessage(Scene scene, WeatherKind nextWeather)
        {
            return m_autoCycleForecastWarningMessage
                .Replace("{RegionName}", scene.RegionInfo.RegionName)
                .Replace("{NextWeather}", WeatherName(nextWeather))
                .Replace("{NextTemperature}", WeatherBaseTemperatureC(nextWeather).ToString("0.#", CultureInfo.InvariantCulture))
                .Replace("{TimeUntilNextForecast}", FormatTimeUntilNextForecast())
                .Replace("{NextForecast}", FormatNextForecast());
        }

