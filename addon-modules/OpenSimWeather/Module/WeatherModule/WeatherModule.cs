        private static Vector3 ReadVector3(IConfig config, string key, Vector3 fallback)
        {
            string raw = config.GetString(key, string.Empty).Trim();
            if (string.IsNullOrEmpty(raw))
                return fallback;

            string[] parts = raw.Split(',');
            if (parts.Length != 3
                || !float.TryParse(parts[0].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float x)
                || !float.TryParse(parts[1].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float y)
                || !float.TryParse(parts[2].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float z))
                return fallback;

            return new Vector3(x, y, z);
        }

        private static Vector4 ReadVector4(IConfig config, string key, Vector4 fallback)
        {
            string raw = config.GetString(key, string.Empty).Trim();
            if (string.IsNullOrEmpty(raw))
                return fallback;

            string[] parts = raw.Split(',');
            if (parts.Length != 4
                || !float.TryParse(parts[0].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float x)
                || !float.TryParse(parts[1].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float y)
                || !float.TryParse(parts[2].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float z)
                || !float.TryParse(parts[3].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out float w))
                return fallback;

            return new Vector4(x, y, z, w);
        }

