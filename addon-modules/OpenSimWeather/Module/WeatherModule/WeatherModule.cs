                "AutoCycleForecastWarningMessage",
                "Weather forecast update: next conditions for {RegionName} are expected to shift to {NextWeather} in {TimeUntilNextForecast}.").Trim();

            if (m_autoCycleEnabled
                && m_autoCycleForecastWarningMinutes > 0
                && m_autoCycleForecastWarningMinutes * 60f >= m_autoCycleHours * 60f * 60f)
            {
                m_log.Warn(
                    "[WEATHER]: AutoCycleForecastWarningMinutes is equal to or longer than AutoCycleHours; "
