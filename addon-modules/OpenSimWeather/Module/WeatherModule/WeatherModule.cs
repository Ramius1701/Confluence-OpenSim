            m_clearTemperatureC = Clamp(config.GetFloat("ClearTemperatureC", m_temperatureC), -100f, 100f);
            m_sunnyTemperatureC = Clamp(config.GetFloat("SunnyTemperatureC", 22f), -100f, 100f);
            m_rainTemperatureC = Clamp(config.GetFloat("RainTemperatureC", 12f), -100f, 100f);
            m_stormTemperatureC = Clamp(config.GetFloat("StormTemperatureC", 9f), -100f, 100f);
            m_snowTemperatureC = Clamp(config.GetFloat("SnowTemperatureC", -2f), -100f, 100f);
            m_blizzardTemperatureC = Clamp(config.GetFloat("BlizzardTemperatureC", -12f), -100f, 100f);
            m_temperatureVarianceC = Clamp(config.GetFloat("TemperatureVarianceC", 3f), 0f, 50f);
            m_announceWeatherInChat = config.GetBoolean("AnnounceWeatherChangesInChat", true);
            m_broadcastWeatherToScripts = config.GetBoolean("BroadcastWeatherToScripts", true);
            m_weatherBroadcastChannel = config.GetInt("WeatherBroadcastChannel", -910088);
            m_autoCyclePressureDriven = string.Equals(
                    config.GetString("AutoCyclePacing", "Random"), "Pressure", StringComparison.OrdinalIgnoreCase);

            if (m_rainTexture == Util.BLANK_TEXTURE_UUID)
                m_log.Warn("[WEATHER]: RainTexture is blank; rain will use viewer billboards and may look rectangular.");
            if (m_snowTexture == Util.BLANK_TEXTURE_UUID)
                m_log.Warn("[WEATHER]: SnowTexture is blank; snow will look like square billboards until a snowflake texture UUID is configured.");

            LoadEnvironmentProfiles(source);

            if (!m_restoreCloudsOnClear && m_adjustClouds)
                m_log.Warn("[WEATHER]: RestoreCloudsOnClear=false can intentionally leave the weather environment active after clear.");
            if (!m_restoreWindOnClear && m_adjustWind)
                m_log.Warn("[WEATHER]: RestoreWindOnClear=false can intentionally leave weather wind parameters active after clear.");
        }

        public void AddRegion(Scene scene)
        {
            if (!m_enabled)
                return;

            m_scene = scene;
            m_scene.EventManager.OnChatFromClient += OnChatFromClient;
            m_scene.EventManager.OnMakeRootAgent += OnMakeRootAgent;
            m_log.InfoFormat(
                "[WEATHER]: Enabled in region {0} on channel {1}",
                scene.RegionInfo.RegionName,
                m_commandChannel);
        }

        public void RemoveRegion(Scene scene)
        {
            StopWebSettingsPolling();
            StopAutoCycle();
            StopActiveAreaRefresh();
            StopAuroraTimer();
            StopLightningSweepTimer();
            RemoveAuroraEmitters();

            Scene activeScene = m_scene;
            if (activeScene != null)
            {
                activeScene.EventManager.OnChatFromClient -= OnChatFromClient;
                activeScene.EventManager.OnMakeRootAgent -= OnMakeRootAgent;
            }

            lock (m_weatherChangeSync)
            {
                ClearWeather(false, true, true);
                m_scene = null;
                m_environmentModule = null;
                m_windModule = null;
            }
        }

        public void RegionLoaded(Scene scene)
        {
            if (!m_enabled)
                return;

            m_environmentModule = scene.RequestModuleInterface<IEnvironmentModule>();
            if (m_adjustClouds && m_environmentModule == null)
            {
                m_log.WarnFormat("[WEATHER]: Cloud changes disabled in {0}; EnvironmentModule is not available.", scene.RegionInfo.RegionName);
            }
            else if (m_adjustClouds)
            {
                // The weather sky is each avatar's own override and is never stored on the region, so a crash leaves nothing behind.
                m_log.DebugFormat("[WEATHER]: Cloud adjustment is enabled in {0} (per avatar; the region environment is not changed).",
                    scene.RegionInfo.RegionName);
            }

            m_windModule = scene.RequestModuleInterface<IWindModule>();
            if (m_adjustWind && m_windModule == null)
            {
                m_log.WarnFormat("[WEATHER]: Region wind changes disabled in {0}; WindModule is not available.", scene.RegionInfo.RegionName);
            }
            else if (m_adjustWind
                && m_windModule.WindActiveModelPluginName != "SimpleRandomWind"
                && m_windModule.WindActiveModelPluginName != "ConfigurableWind")
            {
                m_log.WarnFormat(
                    "[WEATHER]: Wind plugin '{0}' in {1} is not supported; weather will not alter region wind.",
                    m_windModule.WindActiveModelPluginName,
                    scene.RegionInfo.RegionName);
            }

            if (m_cleanupGeneratedObjectsOnStartup)
                CleanupGeneratedObjects();

            HealSavedWeatherSky();
            RefreshExclusionVolumes(true);

            // [Confluence] With the web portal the region has weather only once its owner turns it on (polled below);
            // without it, the ini's Enabled=true is the answer, as before.
            if (UsesWebSettings)
                StartWebSettingsPolling();
            else
                SetRegionActive(true, "the [Weather] ini settings");
        }

        public void Close()
        {
            StopSkyFadeTimer();
            StopWebSettingsPolling();
            StopAutoCycle();
            StopActiveAreaRefresh();
            StopAuroraTimer();
            StopLightningSweepTimer();
            RemoveAuroraEmitters();

            lock (m_weatherChangeSync)
            {
                ClearWeather(false, true, true);
                m_scene = null;
                m_environmentModule = null;
                m_windModule = null;
            }
        }

        private void OnMakeRootAgent(ScenePresence sp)
        {
            if (sp == null || sp.IsDeleted || sp.IsNPC || sp.IsChildAgent || !m_regionActive)
                return;

            // [Confluence] an arrival sees the weather sky too (it is per avatar, see ApplyClouds)
            ViewerEnvironment weatherSky = m_weatherEnvironment;
            if (weatherSky != null)
                SetAvatarSky(sp, null, weatherSky);

            if (m_coverageMode == CoverageMode.ActiveArea && IsPrecipitationWeather(CurrentWeather()))
                QueueActiveAreaRefresh();

            if (!m_sendWeatherIMOnEntry)
                return;

            UUID agentID = sp.UUID;
            Util.FireAndForget(
                o =>
                {
                    if (m_weatherIMDelaySeconds > 0)
                        Thread.Sleep(m_weatherIMDelaySeconds * 1000);

                    SendWeatherIM(agentID);
                },
                null,
                "WeatherModule.EntryIM",
                false);
        }

        private void OnChatFromClient(object sender, OSChatMessage chat)
        {
            if (chat == null || chat.Sender == null || chat.Channel != m_commandChannel)
                return;

            Scene scene = m_scene;
            if (scene == null)
                return;

            string request = chat.Message == null ? string.Empty : chat.Message.Trim();
            if (!IsWeatherCommand(request))
                return;

            IClientAPI client = chat.Sender;
            if (m_estateManagerOnly && !scene.Permissions.IsEstateManager(client.AgentId))
            {
                SendReply(client, "Only estate managers can change weather here.");
                return;
            }

            if (!m_regionActive)
            {
                SendReply(client, "Weather is off in this region. Its owner can turn it on under My Regions on the grid's website.");
                return;
            }

            if (IsStatusCommand(request))
            {
                SendStatus(client);
                return;
            }

            if (!TryResolveWeather(request, out WeatherKind weather))
            {
                SendReply(client, "Use weather rain, weather storm, weather snow, weather blizzard, weather sunny, weather clear, or weather status.");
                return;
            }

            if (weather == WeatherKind.Clear)
            {
                // Explicit "weather clear"/"weather stop" from a person means
                // hands off, not "clear is this cycle's pick" - stop the auto
                // cycle timer entirely rather than letting it silently
                // override this a few minutes/hours later (previously it
                // called ScheduleNextAutoCycle() unconditionally in its
                // finally block regardless of how Clear was reached, so an
                // explicit clear never actually stayed clear). Any other
                // explicit weather command below restarts the timer, since
                // issuing one means the person is actively back in control.
                ClearWeather(true, true);
                UpdateTemperatureForWeather(WeatherKind.Clear);
                AnnounceWeatherChange(WeatherKind.Clear);
                BroadcastWeatherToScripts(WeatherKind.Clear);
                StopAutoCycle();
                SendReply(client, m_autoCycleEnabled
                        ? "Clear. Auto cycle stopped - use any weather command (e.g. \"weather storm\") to resume it."
                        : "Clear.");
                return;
            }

            if (ApplyWeather(weather, client.AgentId))
            {
                StartAutoCycle();
                SendReply(client, string.Format("{0} started.", WeatherName(weather)));
            }
            else
                SendReply(client, "Could not create emitters.");
        }

        private bool ApplyWeather(WeatherKind weather, UUID ownerId)
        {
            lock (m_weatherChangeSync)
            {
                ClearWeather(false, false);

                Scene scene = m_scene;
                if (scene == null)
                    return false;

                List<SceneObjectGroup> created = new List<SceneObjectGroup>();

                try
                {
                    m_weatherOwnerId = ownerId;
                    lock (m_sync)
                        m_currentWeather = weather;
                    UpdateTemperatureForWeather(weather);

                    // Sky/wind changes are near-instant; emitter creation can take
                    // a noticeable moment on large regions. Apply the environment
                    // first so the sky visibly changes before precipitation
                    // appears, not after.
                    ApplyClouds(weather);
                    ApplyWind(weather);

                    if (IsPrecipitationWeather(weather))
                    {
                        RefreshActiveAreaEmittersInternal();
                        StartActiveAreaRefresh();
                    }

                    if (weather == WeatherKind.Storm)
                        StartStormEffects(ownerId);

                    int emitterCount;
                    lock (m_sync)
                        emitterCount = m_emitters.Count;

                    m_log.InfoFormat(
                        "[WEATHER]: Started {0} in {1} with {2} emitters {3}",
                        WeatherName(weather),
                        scene.RegionInfo.RegionName,
                        emitterCount,
                        CoverageModeName(m_coverageMode));

                    AnnounceWeatherChange(weather);
                    BroadcastWeatherToScripts(weather);
                    return true;
                }
                catch (Exception e)
                {
                    StopStormEffects();
                    StopActiveAreaRefresh();
        
                    List<SceneObjectGroup> rollbackEmitters;
                    lock (m_sync)
                    {
                        rollbackEmitters = new List<SceneObjectGroup>(m_emitters);
                        m_emitters.Clear();
                        m_activeEmitterCells.Clear();
                        m_activeEmitterZ.Clear();
                        m_currentWeather = WeatherKind.Clear;
                    }

                    DeleteEmitters(rollbackEmitters);
                    RestoreClouds(true);
                    RestoreWind(true);

                    string regionName = m_scene == null ? "unknown region" : m_scene.RegionInfo.RegionName;
                    m_log.WarnFormat(
                        "[WEATHER]: Could not start {0} in {1}; partial changes were rolled back: {2}",
                        WeatherName(weather),
                        regionName,
                        e.Message);
                    return false;
                }
            }
        }

        private void StartActiveAreaRefresh()
        {
            if (m_coverageMode != CoverageMode.ActiveArea || !IsPrecipitationWeather(CurrentWeather()) || m_scene == null)
                return;

            StopActiveAreaRefresh();
            int period = m_activeAreaRefreshSeconds * 1000;
            m_activeAreaTimer = new Timer(ActiveAreaTimerElapsed, null, period, period);
        }

        private void StopActiveAreaRefresh()
        {
            Timer timer = Interlocked.Exchange(ref m_activeAreaTimer, null);
            if (timer != null)
                timer.Dispose();
        }

        private void QueueActiveAreaRefresh()
        {
            Timer timer = m_activeAreaTimer;
            if (timer != null)
                timer.Change(0, m_activeAreaRefreshSeconds * 1000);
        }

        private void ActiveAreaTimerElapsed(object state)
        {
            if (Interlocked.Exchange(ref m_activeAreaBusy, 1) != 0)
                return;

            try
            {
                lock (m_weatherChangeSync)
                    RefreshActiveAreaEmittersInternal();
            }
            catch (Exception e)
            {
                m_log.WarnFormat("[WEATHER]: Active-area emitter refresh failed: {0}", e.Message);
            }
            finally
            {
                Interlocked.Exchange(ref m_activeAreaBusy, 0);
            }
        }

        /// <summary>
        /// [Confluence] 0.6.0. The emitters around the avatars present: a grid of cells over a circle round each avatar
        /// (spaced so the ground circles of their particles overlap), each emitter a set drop above the avatar it is for,
        /// so rain and snow reach the ground (or the floor the avatar stands on) wherever people are, on any region size.
        /// An avatar under cover, or a cell under a roof, gets none. The particles alive around one avatar stay within
        /// ParticleBudget. Cells no avatar needs any more are removed; an emitter whose avatar climbed or dropped is moved.
        /// </summary>
        private void RefreshActiveAreaEmittersInternal()
        {
            Scene scene = m_scene;
            WeatherKind weather = CurrentWeather();
            if (scene == null || m_coverageMode != CoverageMode.ActiveArea || !IsPrecipitationWeather(weather))
                return;

            PrecipitationParticles.Fall fall = PrecipitationParticles.For(WeatherName(weather));
            if (fall == null)
                return;

            int sizeX = Math.Max(1, (int)scene.RegionInfo.RegionSizeX);
            int sizeY = Math.Max(1, (int)scene.RegionInfo.RegionSizeY);
            float drop = m_precipHeight;
            float spacing = Clamp(PrecipitationParticles.Spread(fall, drop) * 1.5f, 6f, 24f);
            float radius = m_precipRadius;
            float weatherDensity = weather == WeatherKind.Storm || weather == WeatherKind.Blizzard ? 1.5f : 1f;
            int cellsPerAvatar = Math.Max(1, (int)Math.Round(Math.PI * radius * radius / (spacing * spacing)));
            float particlesPerEmitter = m_precipBudget * m_precipDensity * weatherDensity / cellsPerAvatar;

            // cell -> the floor height it rains down to (the highest avatar it is for, standing on whatever it stands on)
            Dictionary<long, float> needed = new Dictionary<long, float>();
            scene.ForEachRootScenePresence(sp =>
            {
                if (sp == null || sp.IsDeleted || sp.IsNPC || sp.IsChildAgent)
                    return;

                Vector3 at = sp.AbsolutePosition;
                float floor = Math.Max(TerrainFloor(at.X, at.Y), at.Z - 1f);
                if (m_suppressAroundCoveredAvatars && RayPointCovered(at.X, at.Y, at.Z + 1.5f, floor + drop))
                    return;

                int minCellX = Math.Max(0, (int)Math.Floor((at.X - radius) / spacing));
                int maxCellX = Math.Min((int)Math.Ceiling(sizeX / spacing) - 1, (int)Math.Floor((at.X + radius) / spacing));
                int minCellY = Math.Max(0, (int)Math.Floor((at.Y - radius) / spacing));
                int maxCellY = Math.Min((int)Math.Ceiling(sizeY / spacing) - 1, (int)Math.Floor((at.Y + radius) / spacing));

                for (int cellX = minCellX; cellX <= maxCellX && needed.Count < m_maxEmitters; cellX++)
                {
                    for (int cellY = minCellY; cellY <= maxCellY && needed.Count < m_maxEmitters; cellY++)
                    {
                        float centerX = Math.Min(sizeX - 1f, (cellX + 0.5f) * spacing);
                        float centerY = Math.Min(sizeY - 1f, (cellY + 0.5f) * spacing);
                        float dx = centerX - at.X;
                        float dy = centerY - at.Y;
                        if (dx * dx + dy * dy > radius * radius)
                            continue;

                        long key = CellKey(cellX, cellY);
                        float cellFloor = Math.Max(floor, TerrainFloor(centerX, centerY));
                        if (!needed.TryGetValue(key, out float have) || cellFloor > have)
                            needed[key] = cellFloor;
                    }
                }
            });

            List<SceneObjectGroup> delete = new List<SceneObjectGroup>();
            lock (m_sync)
            {
                List<long> obsolete = new List<long>();
                foreach (KeyValuePair<long, SceneObjectGroup> pair in m_activeEmitterCells)
                {
                    bool keep = needed.TryGetValue(pair.Key, out float cellFloor)
                        && m_activeEmitterZ.TryGetValue(pair.Key, out float z)
                        && Math.Abs(z - (cellFloor + drop)) < 6f;
                    if (!keep)
                    {
                        obsolete.Add(pair.Key);
                        delete.Add(pair.Value);
                        m_emitters.Remove(pair.Value);
                    }
                }

                foreach (long key in obsolete)
                {
                    m_activeEmitterCells.Remove(key);
                    m_activeEmitterZ.Remove(key);
                }
            }
            DeleteEmitters(delete);

            UUID texture = WeatherTexture(weather);
            foreach (KeyValuePair<long, float> cell in needed)
            {
                lock (m_sync)
                {
                    if (m_activeEmitterCells.ContainsKey(cell.Key))
                        continue;
                }

                DecodeCellKey(cell.Key, out int cellX, out int cellY);
                float posX = Math.Min(sizeX - 1f, (cellX + 0.5f) * spacing);
                float posY = Math.Min(sizeY - 1f, (cellY + 0.5f) * spacing);
                float z = cell.Value + drop;
                if (m_avoidCoveredAreas && RayPointCovered(posX, posY, cell.Value + 1.5f, z))
                    continue;                                   // a roof between this cell's floor and the sky

                Primitive.ParticleSystem particles = PrecipitationParticles.Build(
                    fall, drop, particlesPerEmitter, WeatherWindVector(weather, RandomRange(0.75f, 1.25f)) * 0.25f, texture);
                SceneObjectGroup emitter = CreateEmitter(m_weatherOwnerId, weather, new Vector3(posX, posY, z), particles);
                if (!scene.AddNewSceneObject(emitter, false))
                    continue;

                emitter.RootPart.SendFullUpdateToAllClients();
                emitter.ScheduleGroupForUpdate(PrimUpdateFlags.FullUpdatewithAnimMatOvr);
                lock (m_sync)
                {
                    m_activeEmitterCells[cell.Key] = emitter;
                    m_activeEmitterZ[cell.Key] = z;
                    m_emitters.Add(emitter);
                }
            }
        }

        private static long CellKey(int x, int y)
        {
            return ((long)x << 32) | (uint)y;
        }

        private static void DecodeCellKey(long key, out int x, out int y)
        {
            x = (int)(key >> 32);
            y = (int)(key & 0xffffffffL);
        }

        private void StartAutoCycle()
        {
            StartAutoCycle(m_autoCycleChangeOnStartup);
        }

        /// <param name="changeSoon">first change after AutoCycleStartupDelaySeconds rather than a full interval</param>
        private void StartAutoCycle(bool changeSoon)
        {
            if (!m_autoCycleEnabled || m_scene == null)
                return;

            StopAutoCycle();

            int dueTime = changeSoon
                ? m_autoCycleStartupDelaySeconds * 1000
                : AutoCycleIntervalMS();

            m_autoCycleTimer = new Timer(AutoCycleTimerElapsed, null, Timeout.Infinite, Timeout.Infinite);
            m_autoCycleWarningTimer = new Timer(AutoCycleForecastWarningElapsed, null, Timeout.Infinite, Timeout.Infinite);
            ScheduleAutoCycle(dueTime);

            m_log.InfoFormat(
                "[WEATHER]: Auto cycle enabled in {0}; choices={1}, interval={2:0.##} hours",
                m_scene.RegionInfo.RegionName,
                AutoCycleChoiceNames(),
                m_autoCycleHours);
        }

        private void StopAutoCycle()
        {
            Timer timer = m_autoCycleTimer;
            m_autoCycleTimer = null;
            Timer warningTimer = m_autoCycleWarningTimer;
            m_autoCycleWarningTimer = null;

            if (timer != null)
                timer.Dispose();
            if (warningTimer != null)
                warningTimer.Dispose();

            Interlocked.Exchange(ref m_autoCycleBusy, 0);
            m_nextAutoCycleTicks = 0;
            m_hasPendingAutoCycleWeather = false;
        }

        private void AutoCycleTimerElapsed(object state)
        {
            if (Interlocked.Exchange(ref m_autoCycleBusy, 1) != 0)
                return;

            try
            {
                Scene scene = m_scene;
                if (scene == null)
                    return;

                WeatherKind weather;
                lock (m_sync)
                {
                    weather = m_hasPendingAutoCycleWeather ? m_pendingAutoCycleWeather : PickAutoCycleWeather();
                    m_hasPendingAutoCycleWeather = false;
                }

                if (weather == WeatherKind.Clear)
                {
                    ClearWeather(true, true);
                    UpdateTemperatureForWeather(WeatherKind.Clear);
                    AnnounceWeatherChange(WeatherKind.Clear);
                    BroadcastWeatherToScripts(WeatherKind.Clear);
                    m_log.InfoFormat("[WEATHER]: Auto cycle selected clear in {0}", scene.RegionInfo.RegionName);
                }
                else if (ApplyWeather(weather, UUID.Zero))
                {
                    m_log.InfoFormat(
                        "[WEATHER]: Auto cycle selected {0} in {1}",
                        WeatherName(weather),
                        scene.RegionInfo.RegionName);
                }
                else
                {
                    m_log.WarnFormat(
                        "[WEATHER]: Auto cycle could not start {0} in {1}",
                        WeatherName(weather),
                        scene.RegionInfo.RegionName);
                }
            }
            catch (Exception e)
            {
                string regionName = m_scene == null ? "unknown region" : m_scene.RegionInfo.RegionName;
                m_log.WarnFormat("[WEATHER]: Auto cycle failed in {0}: {1}", regionName, e);
            }
            finally
            {
                Interlocked.Exchange(ref m_autoCycleBusy, 0);
                ScheduleNextAutoCycle();
            }
        }

        private void ScheduleNextAutoCycle()
        {
            ScheduleAutoCycle(AutoCycleIntervalMS());
        }

        private void ScheduleAutoCycle(int dueTimeMS)
        {
            Timer timer = m_autoCycleTimer;
            if (timer == null || m_scene == null)
                return;

            dueTimeMS = Math.Max(1000, dueTimeMS);
            m_nextAutoCycleTicks = DateTime.Now.Ticks + dueTimeMS * 10000L;
            timer.Change(dueTimeMS, Timeout.Infinite);

            ScheduleAutoCycleWarning(dueTimeMS);
        }

        private void ScheduleAutoCycleWarning(int dueTimeMS)
        {
            Timer warningTimer = m_autoCycleWarningTimer;
            if (warningTimer == null || m_autoCycleForecastWarningMinutes <= 0 || string.IsNullOrEmpty(m_autoCycleForecastWarningMessage))
                return;

            int warningLeadMS = m_autoCycleForecastWarningMinutes * 60 * 1000;
            int warningDueMS = dueTimeMS - warningLeadMS;
            if (warningDueMS <= 0)
            {
                warningTimer.Change(Timeout.Infinite, Timeout.Infinite);
                return;
            }

            warningTimer.Change(warningDueMS, Timeout.Infinite);
        }

        private void AutoCycleForecastWarningElapsed(object state)
        {
            Scene scene = m_scene;
            if (scene == null || string.IsNullOrEmpty(m_autoCycleForecastWarningMessage))
                return;

            WeatherKind nextWeather;
            lock (m_sync)
            {
                if (!m_hasPendingAutoCycleWeather)
                {
                    m_pendingAutoCycleWeather = PickAutoCycleWeather();
                    m_hasPendingAutoCycleWeather = true;
                }

                nextWeather = m_pendingAutoCycleWeather;
            }

            string message = FormatForecastWarningMessage(scene, nextWeather);
            scene.ForEachRootScenePresence(sp =>
            {
                if (sp != null && !sp.IsDeleted && sp.ControllingClient != null)
                    SendRegionWeatherMessage(sp, message);
            });
        }

        private int AutoCycleIntervalMS()
        {
            double intervalMS = m_autoCycleHours * 60d * 60d * 1000d;
            return (int)Math.Max(1000d, Math.Min(int.MaxValue, intervalMS));
        }

        private WeatherKind PickAutoCycleWeather()
        {
            WeatherKind current;
            lock (m_sync)
                current = m_currentWeather;

            if (m_autoCyclePressureDriven)
                return PickPressureDrivenWeather(current);

            lock (m_randomSync)
            {
                for (int attempt = 0; attempt < 8; attempt++)
                {
                    WeatherKind weather = m_autoCycleChoices[m_random.Next(m_autoCycleChoices.Count)];
                    if (m_autoCycleChoices.Count == 1 || weather != current)
                        return weather;
                }

                return m_autoCycleChoices[m_random.Next(m_autoCycleChoices.Count)];
            }
        }

        // Fair (Clear/Sunny), moderate (Rain/Snow), and severe (Storm/
        // Blizzard) bands, low pressure = severe - same real-meteorology
        // direction Gemini's reference script used. Deliberately doesn't
        // try to pick Rain vs. Snow (or any hemisphere/season guess) -
        // that's left entirely to whichever of the two an admin actually
        // configured into AutoCycleWeatherChoices, same as the existing
        // random picker already respects that list.
        private static WeatherSeverity SeverityOf(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Storm:
                case WeatherKind.Blizzard:
                    return WeatherSeverity.Severe;
                case WeatherKind.Rain:
                case WeatherKind.Snow:
                    return WeatherSeverity.Moderate;
                default:
                    return WeatherSeverity.Fair;
            }
        }

        private enum WeatherSeverity
        {
            Fair,
            Moderate,
            Severe
        }

        private WeatherKind PickPressureDrivenWeather(WeatherKind current)
        {
            lock (m_randomSync)
            {
                // Small chance each tick of a new pressure system moving in;
                // otherwise keep drifting toward the last-rolled target. This
                // mirrors a real pressure trend building over several ticks
                // instead of resetting every single time.
                if (m_random.NextDouble() < 0.35)
                    m_simulatedPressureTargetHPa = 970f + (float)(m_random.NextDouble() * 60f); // 970-1030 hPa

                m_simulatedPressureHPa +=
                        (m_simulatedPressureTargetHPa - m_simulatedPressureHPa) * 0.45f;

                WeatherSeverity band;
                if (m_simulatedPressureHPa < 995f)
                    band = WeatherSeverity.Severe;
                else if (m_simulatedPressureHPa < 1012f)
                    band = WeatherSeverity.Moderate;
                else
                    band = WeatherSeverity.Fair;

                List<WeatherKind> candidates = new List<WeatherKind>();
                foreach (WeatherKind weather in m_autoCycleChoices)
                {
                    if (SeverityOf(weather) == band)
                        candidates.Add(weather);
                }

                // Nothing configured in this exact band (e.g. only Storm and
                // Sunny are enabled, pressure landed on Moderate) - fall back
                // to the full configured list rather than getting stuck.
                if (candidates.Count == 0)
                    candidates = m_autoCycleChoices;

                for (int attempt = 0; attempt < 8; attempt++)
                {
                    WeatherKind weather = candidates[m_random.Next(candidates.Count)];
                    if (candidates.Count == 1 || weather != current)
                        return weather;
                }

                return candidates[m_random.Next(candidates.Count)];
            }
        }

        private void ParseAutoCycleChoices(string choices)
        {
            m_autoCycleChoices.Clear();

            string[] tokens = (choices ?? string.Empty).Split(',');
            foreach (string rawToken in tokens)
            {
                WeatherKind weather;
                if (TryResolveWeather(rawToken.Trim(), out weather) && !m_autoCycleChoices.Contains(weather))
                    m_autoCycleChoices.Add(weather);
            }

            if (m_autoCycleChoices.Count == 0)
            {
                m_autoCycleChoices.Add(WeatherKind.Storm);
                m_autoCycleChoices.Add(WeatherKind.Rain);
                m_autoCycleChoices.Add(WeatherKind.Snow);
                m_autoCycleChoices.Add(WeatherKind.Blizzard);
                m_autoCycleChoices.Add(WeatherKind.Sunny);
            }
        }

        private string AutoCycleChoiceNames()
        {
            List<string> names = new List<string>(m_autoCycleChoices.Count);
            foreach (WeatherKind weather in m_autoCycleChoices)
                names.Add(WeatherName(weather));

            return string.Join(",", names.ToArray());
        }

        private bool IsCoveredFromSky(float x, float y, float ground, float emitterZ)
        {
            return GetOpenSkyFraction(x, y, 0f, 0f, emitterZ) < 1f;
        }

        private float GetOpenSkyFraction(float centerX, float centerY, float halfWidth, float halfHeight, float emitterZ)
        {
            if (m_scene == null)
                return 1f;

            if (!m_avoidCoveredAreas && !m_useExclusionVolumes)
                return 1f;

            if (!m_scene.SupportsRayCastFiltered() && !m_useExclusionVolumes)
                return 1f;

            int samples = Math.Max(1, m_coverProbeGrid);
            int open = 0;
            int total = 0;

            for (int ix = 0; ix < samples; ix++)
            {
                float fx = samples == 1 ? 0f : ix / (float)(samples - 1) * 2f - 1f;
                for (int iy = 0; iy < samples; iy++)
                {
                    float fy = samples == 1 ? 0f : iy / (float)(samples - 1) * 2f - 1f;
                    float x = centerX + fx * halfWidth;
                    float y = centerY + fy * halfHeight;
                    if (x < 0f || y < 0f || x >= m_scene.RegionInfo.RegionSizeX || y >= m_scene.RegionInfo.RegionSizeY)
                        continue;

                    total++;
                    float ground = m_scene.GetGroundHeight(x, y);
                    if (!RayPointCovered(x, y, ground, emitterZ))
                        open++;
                }
            }

            return total == 0 ? 0f : open / (float)total;
        }

        private bool RayPointCovered(float x, float y, float ground, float emitterZ)
        {
            Scene scene = m_scene;
            if (scene == null)
                return false;

            if (IsInsideExclusionVolume(x, y))
                return true;

            if (!m_avoidCoveredAreas || !scene.SupportsRayCastFiltered())
                return false;

            float startZ = Math.Max(emitterZ + m_coverProbeHeight, ground + m_coverProbeHeight);
            float length = Math.Max(1f, startZ - ground - 0.2f);
            Vector3 start = new Vector3(x, y, startZ);

            try
            {
                RayFilterFlags filter = m_coverIncludesPhantomPrims
                    ? RayFilterFlags.AllPrims
                    : RayFilterFlags.PrimsNonPhantom;

                List<ContactResult> hits = (List<ContactResult>)scene.RayCastFiltered(
                    start,
                    -Vector3.UnitZ,
                    length,
                    m_coverMaxHits,
                    filter);

                if (hits == null || hits.Count == 0)
                    return false;

                foreach (ContactResult hit in hits)
                {
                    SceneObjectPart part = scene.GetSceneObjectPart(hit.ConsumerID);
                    if (part == null)
                        return true;

                    SceneObjectGroup group = part.ParentGroup;
                    if (IsWeatherGeneratedGroup(group))
                        continue;

                    return true;
                }

                return false;
            }
            catch (Exception e)
            {
                m_log.DebugFormat("[WEATHER]: Cover probe failed in {0}: {1}", scene.RegionInfo.RegionName, e.Message);
                return false;
            }
        }

        /// <summary>An emitter prim for the avatar-area rain and snow, with its particles already worked out.</summary>
        private SceneObjectGroup CreateEmitter(UUID ownerId, WeatherKind weather, Vector3 position, Primitive.ParticleSystem particles)
        {
            PrimitiveBaseShape shape = PrimitiveBaseShape.CreateSphere();
            shape.Scale = new Vector3(1.5f, 1.5f, 1.5f);           // see the other CreateEmitter on tiny prims and LOD
            Primitive.TextureEntry textures = shape.Textures;
            textures.DefaultTexture.RGBA = new Color4(1f, 1f, 1f, 0f);
            shape.Textures = textures;

            // upside down: the particles' cone is round the prim's +Z, which then points at the ground
            SceneObjectPart root = new SceneObjectPart(ownerId, shape, position, PrecipitationParticles.EmitterRotation, Vector3.Zero);
            root.Name = GeneratedNamePrefix + " " + WeatherName(weather) + " emitter";
            root.Description = GeneratedDescription;
            root.Scale = shape.Scale;
            root.AddFlag(PrimFlags.Phantom);
            root.AddNewParticleSystem(particles, false);

            SceneObjectGroup group = new SceneObjectGroup(root);
            group.SetGroup(UUID.Zero, null);
            return group;
        }

        private UUID WeatherTexture(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Snow:
                    return m_snowTexture;
                case WeatherKind.Blizzard:
                    return m_blizzardTexture;
                case WeatherKind.Storm:
                    return m_stormTexture;
                case WeatherKind.Rain:
                    return m_rainTexture;
                default:
                    return Util.BLANK_TEXTURE_UUID;
            }
        }

        private Vector2 WeatherWindVector(WeatherKind weather, float variance)
        {
            float strength = WeatherWindStrength(weather);
            if (strength <= 0f)
                return Vector2.Zero;

            float angle = m_windDirectionDegrees + RandomRange(-m_windDirectionVarianceDegrees, m_windDirectionVarianceDegrees);
            double radians = angle * Math.PI / 180d;
            return new Vector2(
                (float)Math.Cos(radians) * strength * variance,
                (float)Math.Sin(radians) * strength * variance);
        }

        private float WeatherWindStrength(WeatherKind weather)
        {
            switch (weather)
            {
                case WeatherKind.Storm:
                    return m_stormWindStrength;
                case WeatherKind.Blizzard:
                    return m_blizzardWindStrength;
                case WeatherKind.Snow:
                    return m_snowWindStrength;
                case WeatherKind.Rain:
                    return m_rainWindStrength;
                default:
                    return 0f;
            }
        }

        // Floored at water height (so deep water never leaves an emitter at/
        // under the surface) and otherwise following terrain where terrain
        // rises above water (hills/mountains), so a building on a hilltop
        // can't defeat a flat water-relative ceiling.
        private float TerrainFloor(float x, float y)
        {
            Scene scene = m_scene;
            if (scene == null)
                return 0f;

            float waterHeight = (float)scene.RegionInfo.RegionSettings.WaterHeight;
            return Math.Max(waterHeight, scene.GetGroundHeight(x, y));
        }

        private float RandomRange(float min, float max)
        {
            return min + (float)RandomUnit() * (max - min);
        }

        private int RandomRange(int min, int max)
        {
            lock (m_randomSync)
                return m_random.Next(min, max);
        }

        private double RandomUnit()
        {
            lock (m_randomSync)
                return m_random.NextDouble();
        }

        private void ClearWeather(bool log, bool restoreState, bool forceRestore = false)
        {
            lock (m_weatherChangeSync)
            {
                StopStormEffects();
                StopActiveAreaRefresh();
    
                List<SceneObjectGroup> emitters;
                lock (m_sync)
                {
                    emitters = new List<SceneObjectGroup>(m_emitters);
                    m_emitters.Clear();
                    m_activeEmitterCells.Clear();
                    m_currentWeather = WeatherKind.Clear;
                }

                DeleteEmitters(emitters);

                if (restoreState)
                {
                    RestoreClouds(forceRestore);
                    RestoreWind(forceRestore);
                }

                if (log && m_scene != null)
                    m_log.InfoFormat("[WEATHER]: Cleared weather in {0}", m_scene.RegionInfo.RegionName);
            }
        }

        private void StartStormEffects(UUID ownerId)
        {
            if (!m_lightningEnabled && (!m_thunderEnabled || m_thunderSound.IsZero()))
                return;

            int generation = Interlocked.Increment(ref m_stormEffectGeneration);
            Util.FireAndForget(
                o => StormEffectLoop(generation, ownerId),
                null,
                "WeatherModule.StormEffects",
                false);
        }

        private void StopStormEffects()
        {
            Interlocked.Increment(ref m_stormEffectGeneration);
        }

        private void StormEffectLoop(int generation, UUID ownerId)
        {
            while (generation == m_stormEffectGeneration && IsCurrentWeather(WeatherKind.Storm))
            {
                Thread.Sleep(RandomRange(m_lightningMinDelayMS, m_lightningMaxDelayMS + 1));

                if (m_scene == null || generation != m_stormEffectGeneration || !IsCurrentWeather(WeatherKind.Storm))
                    return;

                TriggerLightning(ownerId, generation);
            }
        }

        private bool IsCurrentWeather(WeatherKind weather)
        {
            lock (m_sync)
                return m_currentWeather == weather;
        }

        private void TriggerLightning(UUID ownerId, int generation)
        {
            lock (m_weatherChangeSync)
            {
                if (m_scene == null
                    || generation != m_stormEffectGeneration
                    || !IsCurrentWeather(WeatherKind.Storm))
                {
                    return;
                }

                Vector3 position = GetLightningPosition(out float flashHeight);

                if (m_lightningEnabled)
                    CreateLightningFlash(ownerId, position, flashHeight);

                if (m_thunderEnabled && !m_thunderSound.IsZero())
                {
                    Util.FireAndForget(
                        o =>
                        {
                            Thread.Sleep(RandomRange(450, 1900));
                            lock (m_weatherChangeSync)
                            {
                                if (generation == m_stormEffectGeneration && IsCurrentWeather(WeatherKind.Storm))
                                    SendThunder(position);
                            }
                        },
                        null,
                        "WeatherModule.Thunder",
                        false);
                }
            }
        }

        private Vector3 GetLightningPosition(out float flashHeight)
        {
            Scene scene = m_scene;
            int sizeX = Math.Max(1, (int)scene.RegionInfo.RegionSizeX);
            int sizeY = Math.Max(1, (int)scene.RegionInfo.RegionSizeY);
            float marginX = Math.Min(6f, Math.Max(0f, (sizeX - 1f) * 0.25f));
            float marginY = Math.Min(6f, Math.Max(0f, (sizeY - 1f) * 0.25f));
            List<ScenePresence> avatars = new List<ScenePresence>();

            scene.ForEachRootScenePresence(sp =>
            {
                if (sp != null && !sp.IsDeleted && !sp.IsChildAgent)
                    avatars.Add(sp);
            });

            // Bolt length used to be a fixed 26-46m, tuned back when
            // EmitterHeight defaulted to ~18m - centered a couple meters
            // above that, it reached close enough to the ground to read as
            // a real strike. Once EmitterHeight became a sim-wide-consistent
            // ~80m, that same fixed length
            // left the bolt floating entirely between roughly 60-120m up,
            // never visibly reaching the ground at all. Scale the length
            // with EmitterHeight instead so it keeps reaching down to near
            // the ground at any configured height - found live, 2026-09-14.
            flashHeight = Math.Max(12f, (m_emitterHeight - 3f) * RandomRange(0.8f, 1f));
            Vector3 fallback = new Vector3(sizeX * 0.5f, sizeY * 0.5f, flashHeight * 0.5f);
            for (int attempt = 0; attempt < 12; attempt++)
            {
                float x;
                float y;
                if (avatars.Count > 0)
                {
                    ScenePresence avatar = avatars[RandomRange(0, avatars.Count)];
                    x = Clamp(avatar.AbsolutePosition.X + RandomRange(-52f, 52f), marginX, Math.Max(marginX, sizeX - marginX));
                    y = Clamp(avatar.AbsolutePosition.Y + RandomRange(-52f, 52f), marginY, Math.Max(marginY, sizeY - marginY));
                }
                else
                {
                    x = RandomRange(marginX, Math.Max(marginX + 0.01f, sizeX - marginX));
                    y = RandomRange(marginY, Math.Max(marginY + 0.01f, sizeY - marginY));
                }

                float ground = scene.GetGroundHeight(x, y);
                float floorZ = TerrainFloor(x, y);
                // Center the bolt so its bottom sits a couple meters above
                // the ground (visual clearance, no terrain clipping) and its
                // top reaches up toward cloud height - a real strike
                // spanning the two, not a segment floating in between.
                fallback = new Vector3(x, y, floorZ + 2f + flashHeight * 0.5f);
                if (!IsCoveredFromSky(x, y, ground, floorZ + m_emitterHeight))
                    return fallback;
            }

            return fallback;
        }

        private void CreateLightningFlash(UUID ownerId, Vector3 position, float flashHeight)
        {
            PrimitiveBaseShape shape = PrimitiveBaseShape.CreateCylinder();
            shape.Scale = new Vector3(0.55f, 0.55f, flashHeight);

            Primitive.TextureEntry textures = shape.Textures;
            textures.DefaultTexture.TextureID = m_lightningTexture;
            textures.DefaultTexture.RGBA = new Color4(0.96f, 0.98f, 1f, 1f);
            textures.DefaultTexture.Fullbright = true;
            textures.DefaultTexture.Glow = 1f;
            shape.Textures = textures;

            SceneObjectPart root = new SceneObjectPart(ownerId, shape, position, Quaternion.Identity, Vector3.Zero);
            root.Name = GeneratedNamePrefix + " lightning flash";
            root.Description = GeneratedDescription;
            root.Scale = shape.Scale;
            root.AddFlag(PrimFlags.Phantom);
            root.AddFlag(PrimFlags.TemporaryOnRez);

            SceneObjectGroup flash = new SceneObjectGroup(root);
            flash.TemporaryInstance = true;
            flash.SetGroup(UUID.Zero, null);

            if (!m_scene.AddNewSceneObject(flash, false))
                return;

            flash.RootPart.SendFullUpdateToAllClients();
            flash.ScheduleGroupForUpdate(PrimUpdateFlags.FullUpdate);

            m_activeLightningFlashes[flash.UUID] = DateTime.UtcNow;

            Util.FireAndForget(
                o =>
                {
                    Thread.Sleep(RandomRange(420, 820));
                    DeleteLightningFlash(flash);
                },
                null,
                "WeatherModule.LightningFlash",
                false);
        }

        private void DeleteLightningFlash(SceneObjectGroup flash)
        {
            if (flash != null)
                m_activeLightningFlashes.TryRemove(flash.UUID, out _);

            if (m_scene == null || flash == null || flash.IsDeleted)
                return;

            try
            {
                m_scene.DeleteSceneObject(flash, false, false);
            }
            catch (Exception e)
            {
                m_log.DebugFormat("[WEATHER]: Failed to delete lightning flash {0}: {1}", flash.UUID, e.Message);
            }
        }

